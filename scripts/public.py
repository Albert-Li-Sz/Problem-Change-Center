def backup(args) -> Path | None:
    values = read_env(ENV_FILE)
    recipient = os.getenv("PUBLIC_BACKUP_RECIPIENT") or values.get(
        "PUBLIC_BACKUP_RECIPIENT", ""
    )
    plain = getattr(args, "plain", False)
    if not plain:
        if not recipient:
            raise Failure(
                "未配置 PUBLIC_BACKUP_RECIPIENT。在离线电脑运行 age-keygen 生成密钥，"
                f"把 age1… 公钥写入 {ENV_FILE.name}；或用 --plain 生成未加密备份（含邮箱与密码哈希，请自行保管）"
            )
        if not shutil.which("age"):
            raise Failure("未安装 age（Debian/Ubuntu：sudo apt-get install age）")
    directory = Path(values.get("PUBLIC_BACKUP_DIR") or "/srv/p2h/backups")
    owned_directory(directory, os.geteuid(), os.getegid(), getattr(args, "yes", False))
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    suffix = "" if plain else ".age"
    target = directory / f"p2h-{stamp}.dump{suffix}"
    old_mask = os.umask(0o077)
    partial = directory / f".p2h-backup.{secrets.token_hex(4)}"
    try:
        dump = subprocess.Popen(  # noqa: S603
            [
                "docker",
                "compose",
                "--env-file",
                str(ENV_FILE),
                "-f",
                str(COMPOSE_FILE),
                "exec",
                "-T",
                "postgres",
                "pg_dump",
                "-U",
                "p2h_owner",
                "-d",
                "p2h",
                "-Fc",
            ],
            cwd=ROOT,
            stdout=subprocess.PIPE,
        )
        if plain:
            with partial.open("wb") as handle:
                shutil.copyfileobj(dump.stdout, handle)
            sealed = 0
        else:
            sealed = subprocess.run(
                ["age", "-r", recipient, "-o", str(partial)], stdin=dump.stdout
            ).returncode  # noqa: S603,S607
        dump.stdout.close()
        if dump.wait() or sealed or not partial.stat().st_size:
            raise Failure("数据库导出失败；确认 postgres 容器正在运行")
        partial.replace(target)
        # The configuration holds the database and SMTP secrets needed to restore.
        if not plain:
            config = directory / f"p2h-{stamp}.env.age"
            run(["age", "-r", recipient, "-o", str(config), str(ENV_FILE)])
    finally:
        partial.unlink(missing_ok=True)
        os.umask(old_mask)
    keep = int(values.get("PUBLIC_BACKUP_KEEP_DAYS") or 7)
    cutoff = time.time() - keep * 86400
    # Only this tool's dated files in this directory ever expire.
    for old in directory.glob("p2h-*"):
        if (
            re.fullmatch(r"p2h-\d{8}T\d{6}Z\.(dump|env)(\.age)?", old.name)
            and old.stat().st_mtime < cutoff
        ):
            old.unlink()
    say(f"  ✓ 备份完成：{target}（保留 {keep} 天；题包与结果不在备份范围内）")
    return target


def timer(args) -> None:
    """Install a daily systemd timer that runs this script's backup."""
    if platform.system() != "Linux" or not shutil.which("systemctl"):
        raise Failure("自动备份依赖 systemd；其他系统请用 cron 调用 ./public.sh backup")
    user = getpass.getuser()
    service = f"""[Unit]
Description=Encrypted PostgreSQL backup for the P2H public site
After=docker.service

[Service]
Type=oneshot
User={user}
WorkingDirectory={ROOT}
ExecStart={sys.executable} {Path(__file__).resolve()} backup --yes
UMask=0077
"""
    schedule = """[Unit]
Description=Daily P2H public backup

[Timer]
OnCalendar=*-*-* 03:20:00 UTC
RandomizedDelaySec=20m
Persistent=true

[Install]
WantedBy=timers.target
"""
    sudo = [] if os.geteuid() == 0 else ["sudo"]
    with tempfile.TemporaryDirectory() as folder:
        for name, text in (
            ("p2h-backup.service", service),
            ("p2h-backup.timer", schedule),
        ):
            Path(folder, name).write_text(text)
            run(
                [
                    *sudo,
                    "install",
                    "-m",
                    "0644",
                    str(Path(folder, name)),
                    f"/etc/systemd/system/{name}",
                ]
            )
    run([*sudo, "systemctl", "daemon-reload"])
    run([*sudo, "systemctl", "enable", "--now", "p2h-backup.timer"])
    say("  ✓ 已启用每日自动备份（systemctl list-timers p2h-backup.timer）")


def upgrade(args) -> None:
    values = read_env(ENV_FILE)
    if not values:
        raise Failure(f"未找到 {ENV_FILE.name}；请先运行 ./public.sh install")
    if os.getenv("P2H_UPGRADE_STAGE") != "apply":
        if args.no_backup:
            say("已跳过升级前备份。")
        elif values.get("PUBLIC_BACKUP_RECIPIENT") and shutil.which("age"):
            say("升级前备份数据库…")
            backup(args)
        elif not confirm(
            "未配置加密备份，仍要在没有备份的情况下升级吗？", False, assume_yes=args.yes
        ):
            raise Failure(
                "已取消。配置 PUBLIC_BACKUP_RECIPIENT 后重试，或加 --no-backup"
            )
        if not args.no_pull and (ROOT / ".git").exists():
            say("\n更新代码…")
            if run(
                ["git", "status", "--porcelain", "--untracked-files=no"], capture=True
            ).stdout.strip():
                raise Failure(
                    "工作区有未提交的修改；请先处理，或用 --no-pull 只重建当前代码"
                )
            run(["git", "pull", "--ff-only"])
        # Continue with the code that was just pulled, including this script.
        os.environ["P2H_UPGRADE_STAGE"] = "apply"
        os.execv(
            sys.executable,
            [sys.executable, str(Path(__file__).resolve()), *sys.argv[1:]],
        )

    # New settings introduced by a release get their profile defaults here.
    defaults(values)
    apply_profile(values, values["PUBLIC_PROFILE"], overwrite=False)
    apply_image_source(values, values["PUBLIC_IMAGE_SOURCE"])
    write_env(ENV_FILE, values)
    if not doctor(values, quiet=True):
        raise Failure("请先解决上面标记为 ✗ 的问题")
    images(values)

    was_open = sql("SELECT queue_open FROM site_settings WHERE id=1") == "t"
    say("\n暂停任务领取，等待运行中的任务结束…")
    sql("UPDATE site_settings SET queue_open=false WHERE id=1")
    try:
        deadline = time.monotonic() + 35 * 60
        while (
            running := int(sql("SELECT count(*) FROM jobs WHERE status='running'") or 0)
        ) and time.monotonic() < deadline:
            say(f"  仍有 {running} 个任务在运行（Ctrl+C 可放弃升级，队列会恢复）")
            time.sleep(15)
        start(values)
    finally:
        if was_open:
            sql("UPDATE site_settings SET queue_open=true WHERE id=1")
            say("  ✓ 任务队列已恢复")
    run(["docker", "image", "prune", "-f"], check=False, capture=True)
    say("\n升级完成。请登录站点做一次上传、转换、下载的冒烟测试。")


