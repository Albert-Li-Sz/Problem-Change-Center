def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="public.sh", description="公众版一键部署与运维"
    )
    commands = parser.add_subparsers(dest="command")
    for name, text in (
        ("install", "交互式安装或修改配置"),
        ("upgrade", "备份、更新代码、重建并滚动重启"),
    ):
        command = commands.add_parser(name, help=text)
        command.add_argument("--yes", action="store_true", help="不提问，使用现有配置")
    commands.choices["upgrade"].add_argument(
        "--no-pull", action="store_true", help="不执行 git pull"
    )
    commands.choices["upgrade"].add_argument(
        "--no-backup", action="store_true", help="跳过升级前备份"
    )
    command = commands.add_parser("backup", help="加密备份数据库与配置")
    command.add_argument("--plain", action="store_true", help="生成未加密备份")
    command.add_argument("--yes", action="store_true", help=argparse.SUPPRESS)
    commands.add_parser("timer", help="安装每日自动备份的 systemd 定时器")
    commands.add_parser("status", help="容器与健康状态")
    commands.add_parser("doctor", help="检查主机环境与配置")
    command = commands.add_parser("admin", help="创建或重置管理员")
    command.add_argument("email")
    command = commands.add_parser("invite", help="生成邀请码")
    command.add_argument("count", nargs="?", type=int, default=10)
    command = commands.add_parser("logs", help="查看日志")
    command.add_argument("services", nargs="*", default=["api", "worker", "caddy"])
    args = parser.parse_args(argv)
    try:
        if args.command is None:
            if not interactive():
                parser.print_help()
                return 2
            menu(args)
        elif args.command == "install":
            install(args)
        elif args.command == "upgrade":
            upgrade(args)
        elif args.command == "backup":
            backup(args)
        elif args.command == "timer":
            timer(args)
        elif args.command == "status":
            status(args)
        elif args.command == "doctor":
            return 0 if doctor(read_env(ENV_FILE)) else 1
        elif args.command == "admin":
            compose(
                "run",
                "--rm",
                "api",
                "python",
                "-m",
                "app.public.cli",
                "admin",
                args.email,
            )
        elif args.command == "invite":
            compose(
                "run",
                "--rm",
                "-T",
                "api",
                "python",
                "-m",
                "app.public.cli",
                "invite",
                "--count",
                str(args.count),
            )
        elif args.command == "logs":
            compose("logs", "--tail=100", "-f", *args.services, check=False)
    except Failure as problem:
        say(f"\n✗ {problem}")
        return 1
    except KeyboardInterrupt:
        say("\n已中断。")
        return 130
    return 0


if __name__ == "__main__":
    sys.exit(main())
