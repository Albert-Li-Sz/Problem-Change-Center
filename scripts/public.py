def doctor(values: dict[str, str], *, quiet: bool = False) -> bool:
    """Check the host against the configuration. Returns False on a blocker."""
    blockers = 0

    def report(level: str, text: str) -> None:
        nonlocal blockers
        blockers += level == "✗"
        if level != "✓" or not quiet:
            say(f"  {level} {text}")

    say("环境检查")
    if not shutil.which("docker"):
        report("✗", "未找到 docker；请先安装 Docker Engine")
        return False
    server = run(
        ["docker", "version", "--format", "{{.Server.Version}}"],
        check=False,
        capture=True,
    )
    if server.returncode:
        report(
            "✗",
            "无法连接 Docker daemon；确认服务已启动且当前用户可访问 /var/run/docker.sock",
        )
        return False
    engine = server.stdout.strip()
    if version_tuple(engine) == (29, 4, 2):
        report("✗", "Docker 29.4.2 会阻断 32 位 Wine 启动，请升级到 29.4.3 或更新版本")
    elif version_tuple(engine) < (26,):
        report("!", f"Docker {engine} 较旧，建议升级到 29.4.3 或更新版本")
    else:
        report("✓", f"Docker Engine {engine}")
    if run(["docker", "compose", "version"], check=False, capture=True).returncode:
        report("✗", "缺少 Docker Compose v2 插件（docker compose）")
    if platform.system() != "Linux":
        report("!", f"当前系统为 {platform.system()}；生产部署请使用 Linux")
    if platform.machine() not in {"x86_64", "AMD64"}:
        report(
            "!",
            f"CPU 架构为 {platform.machine()}；Wine 任务需要 x86_64，其他架构只能靠模拟运行",
        )

    profile = PROFILES.get(values.get("PUBLIC_PROFILE", ""), {})
    ram, swap = memory_gib()
    if ram and profile:
        if ram < profile["need"] * 0.9:
            report(
                "!",
                f"内存 {ram:.1f} GiB 低于所选档位的 {profile['need']} GiB，满负载时可能触发 OOM",
            )
        else:
            report("✓", f"内存 {ram:.1f} GiB，交换分区 {swap:.1f} GiB")
    if ram and values.get("PUBLIC_JOB_SWAP", "0") != "0" and swap < 3.5:
        report(
            "!",
            f"已配置任务可用交换空间，但主机交换分区只有 {swap:.1f} GiB；"
            "建议创建 4 GiB 以上的 swap，否则大题包会因内存上限失败",
        )

    data = Path(values.get("PUBLIC_DATA_DIR", "/srv/p2h/data"))
    if not data.is_absolute():
        report("✗", "PUBLIC_DATA_DIR 必须是绝对路径")
    elif data.exists():
        # Docker Desktop virtualises ownership, so this only matters on Linux.
        if platform.system() == "Linux" and data.stat().st_uid != 10001:
            report("✗", f"{data} 的属主应为 UID 10001（sudo chown 10001:10001 {data}）")
        free = shutil.disk_usage(data).free / 1024**3
        report(
            "!" if free < 20 else "✓",
            f"数据目录可用空间 {free:.0f} GiB"
            + ("，建议至少 20 GiB" if free < 20 else ""),
        )
    else:
        report("!", f"数据目录 {data} 尚未创建（install 会创建）")

    docker_socket = Path("/var/run/docker.sock")
    if (
        platform.system() == "Linux"
        and docker_socket.exists()
        and values.get("DOCKER_GID")
        not in {
            None,
            str(docker_socket.stat().st_gid),
        }
    ):
        report(
            "✗",
            f"DOCKER_GID={values['DOCKER_GID']} 与 docker.sock 的属组 {docker_socket.stat().st_gid} 不一致",
        )

    runtime = values.get("PUBLIC_RUNNER_RUNTIME", "runc")
    if runtime != "runc":
        runtimes = run(
            ["docker", "info", "--format", "{{json .Runtimes}}"],
            check=False,
            capture=True,
        )
        if f'"{runtime}"' not in (runtimes.stdout or ""):
            report(
                "✗",
                f"Docker 未注册运行时 {runtime}；请先安装，或把 PUBLIC_RUNNER_RUNTIME 改回 runc",
            )
        else:
            report("✓", f"任务运行时 {runtime}")

    domain = values.get("PUBLIC_DOMAIN", "")
    if domain:
        try:
            addresses = sorted({item[4][0] for item in socket.getaddrinfo(domain, 443)})
            report(
                "✓", f"{domain} 解析到 {', '.join(addresses)}；请确认这是本机的公网地址"
            )
        except OSError:
            report(
                "!",
                f"{domain} 暂时无法解析；证书签发需要 A/AAAA 记录指向本机并放行 80/443",
            )
    if values.get("SMTP_HOST"):
        try:
            with socket.create_connection(
                (values["SMTP_HOST"], int(values.get("SMTP_PORT", "587"))), timeout=5
            ):
                report(
                    "✓",
                    f"SMTP {values['SMTP_HOST']}:{values.get('SMTP_PORT', '587')} 可连接",
                )
        except (OSError, ValueError):
            report(
                "!",
                "SMTP 服务器无法连接；注册验证邮件将发不出去（部分云厂商默认封禁发信端口）",
            )
    if values.get("PUBLIC_CAPTCHA", "turnstile") == "turnstile" and not (
        values.get("TURNSTILE_SITE_KEY") and values.get("TURNSTILE_SECRET_KEY")
    ):
        report("✗", "PUBLIC_CAPTCHA=turnstile 但未填写 Turnstile 密钥")
    if ENV_FILE.exists() and ENV_FILE.stat().st_mode & 0o077:
        report("!", f"{ENV_FILE.name} 权限过宽，建议 chmod 600")
    if not values.get("PUBLIC_BACKUP_RECIPIENT"):
        report(
            "!", "尚未配置备份加密公钥（PUBLIC_BACKUP_RECIPIENT），升级前无法自动备份"
        )
    elif not shutil.which("age"):
        report("!", "未安装 age，无法执行加密备份（apt-get install age）")
    return blockers == 0


