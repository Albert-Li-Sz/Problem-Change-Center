def health(timeout: int = 180) -> bool:
    """Wait for the API to answer and the Worker heartbeat to appear."""
    probe = (
        "import urllib.request,urllib.error,sys\n"
        "try:\n"
        "    urllib.request.urlopen('http://127.0.0.1:8000/api/health/status',timeout=5)\n"
        "except Exception:\n"
        "    sys.exit(1)\n"
    )
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if (
            compose(
                "exec", "-T", "api", "python", "-c", probe, check=False, capture=True
            ).returncode
            == 0
        ):
            return True
        time.sleep(5)
    return False


def start(values: dict[str, str]) -> None:
    say("\n启动服务…")
    compose("up", "-d", "--force-recreate", "--remove-orphans", *SERVICES)
    say("等待服务就绪…")
    if not health():
        compose("ps", check=False)
        raise Failure("服务未在 3 分钟内就绪；用 ./public.sh logs 查看原因")
    say(f"  ✓ API 与 Worker 运行正常：https://{values['PUBLIC_DOMAIN']}")


def install(args) -> None:
    values = read_env(ENV_FILE)
    first = not values
    defaults(values)
    if interactive() and not args.yes:
        say("题包转换公益站 · 安装向导（回车保留方括号中的当前值）")
        configure(values)
    if absent := missing(values):
        raise Failure(
            f"{ENV_FILE.name} 缺少：{', '.join(absent)}；请在终端中运行 ./public.sh install 填写"
        )
    write_env(ENV_FILE, values)
    say(f"\n配置已写入 {ENV_FILE}（权限 0600）")
    if not doctor(values):
        raise Failure("请先解决上面标记为 ✗ 的问题，然后重新运行 ./public.sh install")
    if not confirm("\n开始部署？", True, assume_yes=args.yes):
        say("已保存配置，未启动服务。")
        return
    owned_directory(Path(values["PUBLIC_DATA_DIR"]), 10001, 10001, args.yes)
    images(values)
    start(values)
    if first and interactive() and confirm("\n现在创建管理员账号？", True):
        email = ask("管理员邮箱", values["PUBLIC_CONTACT_EMAIL"], check=valid_email)
        compose("run", "--rm", "api", "python", "-m", "app.public.cli", "admin", email)
    if (
        values.get("PUBLIC_BACKUP_RECIPIENT")
        and platform.system() == "Linux"
        and interactive()
    ):
        if confirm("安装每日自动备份（systemd 定时器）？", True):
            timer(args)
    say(
        "\n完成。后续：./public.sh status 查看状态，./public.sh upgrade 升级，./public.sh backup 备份。"
    )
    say("建议先发放 10 个邀请码试运行 72 小时：./public.sh invite 10")


