# ---------------------------------------------------------------- env file


def read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
            value = value[1:-1]
        values[key.strip()] = value
    return values


def format_env(values: dict[str, str]) -> str:
    lines = ["# Generated by ./public.sh; holds secrets, keep it 0600."]
    for key in [*[k for k in ORDER if k in values], *sorted(set(values) - set(ORDER))]:
        value = values[key]
        if "'" in value or "\n" in value:
            raise Failure(f"{key} 不能包含单引号或换行")
        # Compose expands $ in unquoted values; single quotes keep them literal.
        lines.append(
            f"{key}={value}" if _PLAIN.fullmatch(value) else f"{key}='{value}'"
        )
    return "\n".join(lines) + "\n"


def write_env(path: Path, values: dict[str, str]) -> None:
    text = format_env(values)
    descriptor, temporary = tempfile.mkstemp(dir=path.parent, prefix=".env.public.")
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.chmod(temporary, 0o600)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def apply_profile(values: dict[str, str], name: str, *, overwrite: bool = True) -> None:
    """Apply a tier. "custom" and overwrite=False only fill settings that are missing."""
    values["PUBLIC_PROFILE"] = name
    tier = PROFILES.get(name, PROFILES["large"])
    for key, value in tier.items():
        if key.startswith("PUBLIC_"):
            if overwrite and name in PROFILES:
                values[key] = value
            else:
                values.setdefault(key, value)


def apply_image_source(values: dict[str, str], source: str) -> None:
    values["PUBLIC_IMAGE_SOURCE"] = source
    for key, name in IMAGES.items():
        values[key] = f"{REGISTRY}/{name}:public" if source == "pull" else name


# ----------------------------------------------------------------- helpers


def say(text: str = "") -> None:
    print(text, flush=True)


def run(command: list[str], *, check: bool = True, capture: bool = False, **kwargs):
    result = subprocess.run(  # noqa: S603 - fixed argv, never a shell
        command,
        cwd=ROOT,
        text=True,
        stdout=subprocess.PIPE if capture else None,
        stderr=subprocess.PIPE if capture else None,
        **kwargs,
    )
    if check and result.returncode:
        detail = (result.stderr or "").strip().splitlines()[-1:] if capture else []
        raise Failure(
            f"命令失败：{' '.join(command)}" + (f"\n  {detail[0]}" if detail else "")
        )
    return result


def compose(*args: str, **kwargs):
    return run(
        [
            "docker",
            "compose",
            "--env-file",
            str(ENV_FILE),
            "-f",
            str(COMPOSE_FILE),
            *args,
        ],
        **kwargs,
    )


def interactive() -> bool:
    return sys.stdin.isatty()


def ask(prompt: str, default: str = "", *, secret: bool = False, check=None) -> str:
    """Prompt until valid. Enter keeps the current value; secrets are not echoed."""
    shown = "已设置，回车保留" if secret and default else default
    while True:
        text = f"{prompt}" + (f" [{shown}]" if shown else "") + ": "
        answer = (getpass.getpass(text) if secret else input(text)).strip() or default
        problem = check(answer) if check else None
        if not problem:
            return answer
        say(f"  ✗ {problem}")


def confirm(prompt: str, default: bool = True, *, assume_yes: bool = False) -> bool:
    if assume_yes or not interactive():
        return default
    answer = input(f"{prompt} [{'Y/n' if default else 'y/N'}]: ").strip().lower()
    return default if not answer else answer in {"y", "yes", "是"}


def choose(prompt: str, options: list[tuple[str, str]], default: str) -> str:
    say(prompt)
    for index, (key, label) in enumerate(options, start=1):
        say(f"  {index}) {label}" + ("（当前）" if key == default else ""))
    keys = [key for key, _ in options]
    while True:
        answer = input(f"选择 [{keys.index(default) + 1}]: ").strip()
        if not answer:
            return default
        if answer.isdigit() and 1 <= int(answer) <= len(keys):
            return keys[int(answer) - 1]
        say("  ✗ 请输入列表中的序号")


def version_tuple(text: str) -> tuple[int, ...]:
    return tuple(int(part) for part in re.findall(r"\d+", text)[:3])


def memory_gib() -> tuple[float, float]:
    """Host RAM and swap in GiB; zeros when /proc/meminfo is unavailable."""
    try:
        text = Path("/proc/meminfo").read_text()
    except OSError:
        return 0.0, 0.0
    found = {m[1]: int(m[2]) / 1024**2 for m in re.finditer(r"(\w+):\s+(\d+) kB", text)}
    return found.get("MemTotal", 0.0), found.get("SwapTotal", 0.0)


def suggested_profile() -> str:
    ram, _ = memory_gib()
    if ram and ram < 15:
        return "small"
    if ram and ram < 60:
        return "medium"
    return "large" if ram else "small"


def valid_domain(value: str) -> str | None:
    if not re.fullmatch(
        r"(?=.{1,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}", value
    ):
        return "请输入纯域名，例如 convert.example.org（不含 https:// 和路径）"
    return None


def valid_email(value: str) -> str | None:
    return (
        None if re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", value) else "邮箱格式不正确"
    )


def required(value: str) -> str | None:
    return None if value else "不能为空"


def valid_networks(value: str) -> str | None:
    import ipaddress

    try:
        for part in value.split():
            ipaddress.ip_network(part, strict=False)
    except ValueError:
        return "请输入以空格分隔的 CIDR，例如 203.0.113.7/32 2001:db8::/48"
    return None if value.split() else "不能为空"


